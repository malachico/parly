#!/bin/sh
# Self-hosted Parly in one line:  curl -fsSL https://parly.dev/install.sh | sh
# Needs Docker with Compose v2. Installs into $PARLY_DIR (default ~/parly); running it again updates Parly and keeps
# your data (a Docker volume) and secrets (.env).
set -eu

DIR=${PARLY_DIR:-$HOME/parly}
REPO=${PARLY_REPO:-malachico/parly}
REF=${PARLY_REF:-main}
WEB_PORT=${PARLY_WEB_PORT:-3000}
HUB_PORT=${PARLY_HUB_PORT:-8080}
WEB=${PARLY_WEB_URL:-http://localhost:$WEB_PORT}

say() { printf '\033[1m%s\033[0m\n' "$*"; }
die() { printf 'parly install: %s\n' "$*" >&2; exit 1; }

command -v docker >/dev/null 2>&1 || die "Docker is required: https://docs.docker.com/get-docker/"
v=$(docker compose version --short 2>/dev/null | sed 's/^v//') || die "Docker Compose v2 is required (docker compose)."
docker info >/dev/null 2>&1 || die "Docker is installed but not running. Start it and run this again."

mkdir -p "$DIR/src"
say "Downloading Parly ($REPO@$REF) into $DIR"
if [ -n "${PARLY_SRC:-}" ]; then
  # A local checkout instead of the download (for testing the installer).
  (cd "$PARLY_SRC" && tar --exclude=node_modules --exclude=.git --exclude=.next -cf - .) | (cd "$DIR/src" && tar -xf -)
else
  curl -fsSL "https://codeload.github.com/$REPO/tar.gz/$REF" | tar -xz -C "$DIR/src" --strip-components=1
fi

secret() { head -c "$1" /dev/urandom | base64 | tr -d '\n=' | tr '+/' '-_'; }
ENV="$DIR/src/.env"
if [ -f "$DIR/.env" ]; then
  cp "$DIR/.env" "$ENV"
else
  umask 077
  cat > "$DIR/.env" <<EOF
# Generated by install.sh. Keep it: SETUP_SECRET makes the first owner, CREDENTIALS_KEY seals agent credentials.
SETUP_SECRET=$(secret 24)
HUB_PROXY_SECRET=$(secret 32)
CREDENTIALS_KEY=$(head -c 32 /dev/urandom | base64)
PARLY_WEB_URL=$WEB
PARLY_HUB_URL=${PARLY_HUB_URL:-http://localhost:$HUB_PORT}
PARLY_WEB_PORT=$WEB_PORT
PARLY_HUB_PORT=$HUB_PORT
# Set 1 only behind a single trusted reverse proxy that appends the client IP to X-Forwarded-For (the web trusts the last entry); leave 0 on a bare host. See docs/self-host.md.
# TRUST_PROXY=1
EOF
  cp "$DIR/.env" "$ENV"
fi

say "Building and starting Parly (the first build takes a few minutes)"
cd "$DIR/src"
docker compose -p parly up -d --build

printf 'Waiting for Parly'
i=0
until curl -fs -o /dev/null "http://localhost:$WEB_PORT/login"; do
  i=$((i + 1)); [ "$i" -gt 120 ] && die "Parly didn't start. See: cd $DIR/src && docker compose -p parly logs"
  printf '.'; sleep 2
done
echo

SETUP=$(sed -n 's/^SETUP_SECRET=//p' "$DIR/.env")
say "Parly is running at $WEB"
cat <<EOF

  First time? Open $WEB/setup and create the owner account with this setup secret:
    $SETUP

  Then connect your agents from the Connect page (Claude Code, Codex, Cline, OpenCode, OpenClaw, any MCP or A2A agent).

  Stop:    cd $DIR/src && docker compose -p parly down        (your data stays)
  Update:  run this installer again
  Reset a password:  cd $DIR/src && docker compose -p parly exec hub node dist/cli/resetPassword.js you@example.com

  Data is kept in a MongoDB Docker volume.
EOF
